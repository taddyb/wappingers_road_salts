"""Regenerate the line-number references used by response_to_reviewers.tex.

The response letter cites changes as {L123}: line numbers in the latexdiff
highlighted-changes manuscript (revisions_diff.pdf). revisions.tex carries
\\linelabel{L:key} markers (package lineno); this script

  1. runs latexdiff original.tex revisions.tex > revisions_diff.tex,
  2. builds revisions_diff.tex with tectonic, keeping the aux file,
  3. reads the line number of every \\newlabel{L:key} from the aux file,
  4. writes letter_linerefs.tex (\\Lref{L:key} -> line number),
  5. deletes the intermediate files (the .pdf and .tex are kept).

Run from anywhere after editing revisions.tex:
    .venv/bin/python src/letter_linerefs.py
then rebuild the letter: tectonic response_to_reviewers.tex
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIFF = ROOT / "revisions_diff.tex"
OUT = ROOT / "letter_linerefs.tex"
INTERMEDIATE = [".aux", ".bbl", ".blg", ".out", ".log", ".toc"]


def main():
    revisions = (ROOT / "revisions.tex").read_text()
    expected = re.findall(r"\\linelabel\{(L:[^}]+)\}", revisions)
    if len(expected) != len(set(expected)):
        sys.exit("duplicate \\linelabel keys in revisions.tex")

    with open(DIFF, "w") as fh:
        subprocess.run(["latexdiff", "original.tex", "revisions.tex"],
                       cwd=ROOT, stdout=fh, check=True,
                       stderr=subprocess.DEVNULL)

    # latexdiff turns a deleted numbered equation into an unnumbered displaymath and
    # comments out its \label, so struck-out text that refers to it prints "??".
    # Restore it as a numbered equation that keeps its label.
    diff = DIFF.read_text()
    diff = re.sub(r"\\begin\{displaymath\}(\s*\\DIFdel\{.*?)\s*%DIFDELCMD < \\label\{([^}]+)\}%%%\n\}\\end\{displaymath\}",
                  lambda m: "\\begin{equation}" + m.group(1) + "}\\label{" + m.group(2) + "}\n\\end{equation}",
                  diff, flags=re.S)
    DIFF.write_text(diff)

    subprocess.run(["tectonic", "--keep-intermediates", "revisions_diff.tex"],
                   cwd=ROOT, check=True, capture_output=True)

    aux = (ROOT / "revisions_diff.aux").read_text()
    found = dict(re.findall(r"\\newlabel\{(L:[^}]+)\}\{\{(\d+)\}", aux))

    missing = sorted(set(expected) - set(found))
    if missing:
        sys.exit(f"labels missing from the diff build: {missing}")

    lines = [
        "% Generated by src/letter_linerefs.py. Do not edit by hand.",
        "% Maps each \\linelabel key in revisions.tex to its line number in",
        "% revisions_diff.pdf (the highlighted-changes manuscript).",
    ]
    for key in expected:
        lines.append(f"\\expandafter\\def\\csname Lref@{key}\\endcsname{{{found[key]}}}")
    lines.append(r"\newcommand{\Lref}[1]{\ifcsname Lref@#1\endcsname"
                 r"\csname Lref@#1\endcsname\else\textbf{??}\fi}")
    OUT.write_text("\n".join(lines) + "\n")

    for ext in INTERMEDIATE:
        (ROOT / f"revisions_diff{ext}").unlink(missing_ok=True)
    print(f"wrote {OUT.name}: {len(expected)} labels")


if __name__ == "__main__":
    main()
