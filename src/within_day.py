"""Within-single-survey-day zone contrasts (revision round, WP0).

Decision D0(a): zones are compared only within one survey day; no pooling
across days, no day covariate, no offset correction.

Produces
  figures/table1_revised.tex            main contrast table (booktabs)
  figures/table1_revised_support.tex    lag-1 autocorrelation / n_eff / road distance
  data/salinity_tidy.csv                tidy SC data (also used by the appendix)
  figures/appendix_data.tex             longtable of every SC measurement
and prints (i) within-zone mean+/-SD, (ii) contrasts, (iii) day-offset overlap
analysis (sec. 0b of docs/revision_plan.md), (iv) road distance per zone/day.

Autocorrelation rule (R1.8): for each contrast on one day, residuals
r = x - (zone mean) are pooled in along-channel order over the two zones and
rho = sum(r_t r_{t+1}) / sum(r_t^2) (lag-1, no mean re-centring, zones' means
already removed). Negative rho is set to 0 (no inflation of n); rho is capped
at 0.9. n_eff = n (1-rho)/(1+rho) applied to each zone, floored at 2 and capped
at n. The Welch test is then repeated with n_eff in place of n (df by
Welch-Satterthwaite with n_eff). With 3-point zones rho is essentially
unestimable, so this is a sensitivity check, not a correction.

Run:  .venv/bin/python src/within_day.py
"""
from pathlib import Path
import numpy as np
import pandas as pd
from scipy import stats

from wappingers import (tidy_salinity, CONTRASTS, haversine_m, load_roads_metric,
                        nearest_dist_m, DATA, REPO)

FIG = REPO / "figures"
RHO_CAP = 0.9


def zone_tidy():
    t = tidy_salinity()
    t["road_m"] = nearest_dist_m(t["lat"], t["lon"], load_roads_metric())
    return t


def welch(up, dn, n_up=None, n_dn=None):
    """Welch t of (dn - up) with optional effective sample sizes."""
    n1 = len(up) if n_up is None else n_up
    n2 = len(dn) if n_dn is None else n_dn
    v1, v2 = up.var(ddof=1) / n1, dn.var(ddof=1) / n2
    se = np.sqrt(v1 + v2)
    d = dn.mean() - up.mean()
    df = (v1 + v2) ** 2 / (v1 ** 2 / (n1 - 1) + v2 ** 2 / (n2 - 1))
    t = d / se
    p = 2 * stats.t.sf(abs(t), df)
    h = stats.t.ppf(0.975, df) * se
    return dict(delta=d, se=se, t=t, df=df, p=p, lo=d - h, hi=d + h)


def pooled_rho(up, dn):
    r = np.concatenate([up - up.mean(), dn - dn.mean()])  # transect order: up then down
    den = (r ** 2).sum()
    rho = (r[:-1] * r[1:]).sum() / den if den > 0 else 0.0
    return rho


def neff(n, rho):
    rr = min(max(rho, 0.0), RHO_CAP)
    return float(min(n, max(2.0, n * (1 - rr) / (1 + rr))))


def lag1(x):
    x = np.asarray(x, float) - np.mean(x)
    return float((x[:-1] * x[1:]).sum() / (x ** 2).sum())


def contrasts(t):
    rows = []
    for name, a, b, kind in CONTRASTS:
        for date, g in t.groupby("date"):
            ga, gb = g[g.zone == a], g[g.zone == b]
            if len(ga) < 2 or len(gb) < 2:
                continue
            # Both zones must lie on one transect (they do by construction)
            tr = sorted(set(ga.transect) | set(gb.transect))
            up, dn = ga.sort_values("dist_m")["EC"].to_numpy(), gb.sort_values("dist_m")["EC"].to_numpy()
            if len(tr) > 1:   # zones on different transects (D on 26 Oct: upper vs lower, ~1.1 km gap)
                print("  skipped: contrast", name, date, "spans transects", tr)
                continue
            w = welch(up, dn)
            mw = stats.mannwhitneyu(dn, up, alternative="two-sided")
            rho = pooled_rho(up, dn)
            n1e, n2e = neff(len(up), rho), neff(len(dn), rho)
            we = welch(up, dn, n1e, n2e)
            rows.append(dict(
                contrast=name, zones=f"{a}$\\rightarrow${b}", kind=kind, date=date, transect="+".join(tr),
                n1=len(up), n2=len(dn), m1=up.mean(), s1=up.std(ddof=1), m2=dn.mean(), s2=dn.std(ddof=1),
                **{k: w[k] for k in ("delta", "lo", "hi", "t", "df", "p")},
                U=mw.statistic, mwp=mw.pvalue, rho=rho, n1e=n1e, n2e=n2e,
                p_eff=we["p"], df_eff=we["df"], t_eff=we["t"],
                road1=ga.road_m.median(), road2=gb.road_m.median(),
                ec_temp1=ga.Temp.mean(), ec_temp2=gb.Temp.mean()))
    return pd.DataFrame(rows)


def fmt_p(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


DATE_FMT = {"2018-09-28": "28 Sep", "2018-10-05": "5 Oct", "2018-10-19": "19 Oct", "2018-10-26": "26 Oct"}


def write_tables(c):
    L = [r"% Auto-generated by src/within_day.py -- do not edit by hand.",
         r"% Within-single-day contrasts. Delta = downstream - upstream (uS/cm). n<=3 in a zone: interpret with great caution.",
         r"\begin{tabular}{llllrrrrrrrr}", r"\toprule",
         r"Contr. & Boundary & Date & Zones & $n_1,n_2$ & Up (mean$\pm$SD) & Down (mean$\pm$SD) & "
         r"$\Delta$ [95\% CI] & Welch $t$ (df) & $p$ & $U$ & $p_{\mathrm{MW}}$ \\", r"\midrule"]
    for _, r in c.iterrows():
        small = r"$^{\dagger}$" if min(r.n1, r.n2) < 5 else ""
        L.append(f"{r.contrast} & {r.kind} & {DATE_FMT[r.date]} & {r.zones} & {r.n1},{r.n2}{small} & "
                 f"{r.m1:.1f}$\\pm${r.s1:.1f} & {r.m2:.1f}$\\pm${r.s2:.1f} & "
                 f"{r.delta:+.1f} [{r.lo:+.1f}, {r.hi:+.1f}] & {r.t:.2f} ({r.df:.1f}) & {fmt_p(r.p)} & "
                 f"{r.U:.0f} & {fmt_p(r.mwp)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"% $^{\dagger}$ one zone has fewer than 5 points (add to the caption)."]
    (FIG / "table1_revised.tex").write_text("\n".join(L) + "\n")
    S = [r"% Auto-generated by src/within_day.py -- do not edit by hand.",
         r"\begin{tabular}{lllrrrrrrr}", r"\toprule",
         r"Contr. & Date & Zones & $\hat\rho_1$ & $n_{\mathrm{eff},1}$ & $n_{\mathrm{eff},2}$ & "
         r"$p$ (Welch) & $p$ ($n_{\mathrm{eff}}$) & \multicolumn{2}{c}{Median road dist. (m)} \\",
         r"\cmidrule(lr){9-10}", r" & & & & & & & & up & down \\", r"\midrule"]
    for _, r in c.iterrows():
        S.append(f"{r.contrast} & {DATE_FMT[r.date]} & {r.zones} & {r.rho:.2f} & {r.n1e:.1f} & {r.n2e:.1f} & "
                 f"{fmt_p(r.p)} & {fmt_p(r.p_eff)} & {r.road1:.0f} & {r.road2:.0f} \\\\")
    S += [r"\bottomrule", r"\end{tabular}"]
    (FIG / "table1_revised_support.tex").write_text("\n".join(S) + "\n")


def write_appendix(t):
    cols = ["paper_site", "field_site", "date", "transect", "dist_m", "lat", "lon", "EC", "Temp", "zone", "InFault"]
    out = t[cols].copy()
    out.insert(2, "field_row", t["field_row"])
    out.to_csv(DATA / "salinity_tidy.csv", index=False, float_format="%.5f")
    L = [r"% Auto-generated by src/within_day.py. Requires \usepackage{longtable,booktabs}.",
         r"{\footnotesize",
         r"\begin{longtable}{rrrlrrrrrll}",
         r"\caption{All specific-conductance (SC) measurements, 28 September--26 October 2018 survey. Distance is along-channel from the "
         r"upstream end of each single-day transect (haversine sum of GPS fixes).}\label{tab:appendix_data}\\",
         r"\toprule Site & Field & Pt & Date & Dist (m) & Lat & Lon & SC & $T$ & Zone & Fault \\ \midrule \endfirsthead",
         r"\toprule Site & Field & Pt & Date & Dist (m) & Lat & Lon & SC & $T$ & Zone & Fault \\ \midrule \endhead",
         r"\bottomrule \endfoot"]
    for _, r in out.iterrows():
        z = r.zone if isinstance(r.zone, str) else "--"
        L.append(f"{r.paper_site} & {r.field_site} & {r.field_row} & {r.date} & {r.dist_m:.0f} & {r.lat:.5f} & {r.lon:.5f} & "
                 f"{r.EC:.1f} & {r.Temp:.1f} & {z} & {r.InFault} \\\\")
    L += [r"\end{longtable}", r"}"]
    (FIG / "appendix_data.tex").write_text("\n".join(L) + "\n")


def overlap_analysis(t, radius=120.0):
    a = t[t.date == "2018-10-19"].reset_index(drop=True)
    b = t[t.date == "2018-10-26"].reset_index(drop=True)
    print("\n== Day offset: each 19 Oct point -> nearest 26 Oct point within %d m ==" % radius)
    rows = []
    for _, r in a.iterrows():
        d = haversine_m(r.lat, r.lon, b.lat.to_numpy(), b.lon.to_numpy())
        j = int(np.argmin(d))
        if d[j] <= radius:
            rows.append(dict(f19=r.field_row, tr26=b.transect[j], f26=b.field_row[j], d=d[j],
                             ec19=r.EC, ec26=b.EC[j], off=b.EC[j] - r.EC, dT=b.Temp[j] - r.Temp))
    o = pd.DataFrame(rows)
    print(o.round(2).to_string(index=False))
    print("n=%d offset mean %.1f SD %.1f range %.1f..%.1f; distance range %.0f..%.0f m"
          % (len(o), o.off.mean(), o.off.std(ddof=1), o.off.min(), o.off.max(), o.d.min(), o.d.max()))
    nine = o[(o.d <= 60) & (o.tr26 == "S3-26Oct-upper")]
    print("site-3/site-5 pairs <=60 m: n=%d, offset %.1f..%.1f (mean %.1f)" % (len(nine), nine.off.min(), nine.off.max(), nine.off.mean()))
    # mutual nearest (each 26 Oct upper-transect point to nearest 19 Oct point)
    print("\n-- reverse: each 26 Oct (upper, field site 5) point -> nearest 19 Oct point --")
    rr = []
    for _, r in b[b.transect == "S3-26Oct-upper"].iterrows():
        d = haversine_m(r.lat, r.lon, a.lat.to_numpy(), a.lon.to_numpy())
        j = int(np.argmin(d))
        rr.append(dict(f26=r.field_row, f19=a.field_row[j], d=d[j], off=r.EC - a.EC[j]))
    rr = pd.DataFrame(rr); print(rr.round(2).to_string(index=False))
    s19 = a[a.transect == "S3-19Oct"].iloc[-1]; s26 = b[b.transect == "S3-26Oct-lower"].iloc[0]
    d = haversine_m(s19.lat, s19.lon, s26.lat, s26.lon)
    print("\nSeam: site3 last (EC %.1f) vs site4 first (EC %.1f): %.1f m apart, offset %+.1f" % (s19.EC, s26.EC, d, s26.EC - s19.EC))
    print("Site 4 start vs site 5 end gap: %.0f m" % haversine_m(b[b.transect=='S3-26Oct-upper'].iloc[-1].lat,
          b[b.transect=='S3-26Oct-upper'].iloc[-1].lon, s26.lat, s26.lon))
    return o


def main():
    t = zone_tidy()
    print("== Within-zone, within-day mean +/- SD ==")
    g = t.dropna(subset=["zone"]).groupby(["zone", "date", "transect"]).EC.agg(["size", "mean", "std", "min", "max"])
    print(g.round(2).to_string())
    c = contrasts(t)
    pd.set_option("display.width", 250)
    print("\n== Contrasts (Delta = down - up) ==")
    print(c[["contrast", "date", "n1", "n2", "m1", "s1", "m2", "s2", "delta", "lo", "hi", "t", "df", "p", "U", "mwp"]].round(4).to_string(index=False))
    print("\n== Autocorrelation / n_eff ==")
    print(c[["contrast", "date", "rho", "n1e", "n2e", "t_eff", "df_eff", "p", "p_eff"]].round(4).to_string(index=False))
    print("\n== Lag-1 autocorrelation of raw SC along each transect ==")
    for tr, s in t.groupby("transect", sort=False):
        s = s.sort_values("dist_m")
        print(f"{tr:16s} n={len(s):2d} rho1(raw SC)={lag1(s.EC):.2f}")
    print("\n== Road distance (m) to nearest major road (S1100+S1200): per zone & day (median [min,max]) ==")
    rz = t.dropna(subset=["zone"]).groupby(["zone", "date"]).road_m.agg(["size", "median", "min", "max"])
    print(rz.round(0).to_string())
    print("per-transect median:", t.groupby("transect", sort=False).road_m.median().round(0).to_dict())
    print("InFault points road dist:", t[t.InFault == "yes"].groupby("transect").road_m.median().round(0).to_dict())
    write_tables(c); write_appendix(t)
    overlap_analysis(t)
    t.to_csv(DATA / "salinity_tidy_with_roads.csv", index=False, float_format="%.5f")


if __name__ == "__main__":
    main()
